#!/usr/bin/env python3
"""Regenerate skills/design-md/catalog.md from README.md and design-md/*/DESIGN.md.

Run from anywhere: python3 scripts/build-skill-catalog.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
DESIGN_DIR = ROOT / "design-md"
OUT = ROOT / "skills" / "design-md" / "catalog.md"

ENTRY = re.compile(r"^- \[\*\*(?P<name>.+?)\*\*\]\(https://getdesign\.md/(?P<slug>[^/]+)/design-md\) - (?P<desc>.+)$")


def readme_sections():
    """Return [(category, [(slug, name, desc), ...]), ...] from the README collection."""
    text = README.read_text(encoding="utf-8")
    collection = text.split("## Collection", 1)[1].split("\n## ", 1)[0]
    sections, current = [], None
    for line in collection.splitlines():
        if line.startswith("### "):
            current = (line[4:].strip(), [])
            sections.append(current)
        elif current and (m := ENTRY.match(line.strip())):
            current[1].append((m["slug"], m["name"], m["desc"].strip()))
    return sections


def fallback_entry(slug):
    """Name and description for a design that is not listed in the README."""
    text = (DESIGN_DIR / slug / "DESIGN.md").read_text(encoding="utf-8")
    desc = re.search(r"^description:\s*(.+)$", text, re.M)
    desc = desc[1].strip() if desc else ""
    desc = desc.removeprefix("An inspired interpretation of ").split(" — ")[-1]
    desc = desc.split(". ")[0].rstrip(".")
    desc = desc[:1].upper() + desc[1:]
    return slug.replace("-", " ").title(), desc


def design_format(slug):
    text = (DESIGN_DIR / slug / "DESIGN.md").read_text(encoding="utf-8")
    return "tokens" if text.startswith("---") else "prose"


def main():
    sections = readme_sections()
    listed = {slug for _, entries in sections for slug, _, _ in entries}
    on_disk = sorted(p.name for p in DESIGN_DIR.iterdir() if (p / "DESIGN.md").is_file())
    missing = [s for s in on_disk if s not in listed]
    if missing:
        sections.append(("Other", [(s, *fallback_entry(s)) for s in missing]))

    lines = [
        "# DESIGN.md Catalog",
        "",
        "<!-- Generated by scripts/build-skill-catalog.py. Do not edit by hand. -->",
        "",
        f"{len(on_disk)} design systems. The file for `<slug>` is `design-md/<slug>/DESIGN.md` at the repository root.",
        "",
        "Format: `tokens` = YAML front matter with named tokens (`{colors.primary}`) plus Overview/Colors/Typography/Layout/Elevation & Depth/Shapes/Components/Do's and Don'ts sections; "
        "`prose` = numbered sections 1-9 ending in an Agent Prompt Guide.",
        "",
    ]
    for category, entries in sections:
        entries = [e for e in entries if e[0] in on_disk]
        if not entries:
            continue
        lines += [f"## {category}", "", "| Slug | Name | Format | Look |", "|---|---|---|---|"]
        for slug, name, desc in entries:
            lines.append(f"| `{slug}` | {name} | {design_format(slug)} | {desc.replace('|', '/')} |")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(on_disk)} designs)")


if __name__ == "__main__":
    main()
